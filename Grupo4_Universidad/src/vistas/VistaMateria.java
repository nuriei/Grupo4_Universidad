private void cargarMaterias() {
        
        modeloTabla.setRowCount(0);
        for (Materia m : materiaData.listarTodasLasMaterias()) {
            modeloTabla.addRow(new Object[]{
                m.getId_materia(),
                m.getNombre(),
                m.isActivo() ? "Activo" : "Inactivo"
            });
        }
}
